from io import BytesIO
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

def generate_screening_pdf(record: dict) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=18*mm, leftMargin=18*mm, topMargin=15*mm, bottomMargin=15*mm)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="SmallNote", parent=styles["BodyText"], fontSize=8, leading=10, textColor=colors.HexColor("#444444")))
    story = [
        Paragraph("DRISHTI CARE", styles["Title"]),
        Paragraph("Diabetic Retinopathy Screening Workflow Report", styles["Heading2"]),
        #Paragraph("DEMONSTRATION / RESEARCH OUTPUT — NOT A MEDICAL DIAGNOSIS", styles["Heading3"]),
        Spacer(1, 6*mm),
    ]
    data = [
        ["Screening ID", str(record.get("screening_id", "N/A"))],
        ["Patient reference", str(record.get("patient_ref", "N/A"))],
        ["Eye", str(record.get("eye", "N/A"))],
        ["Screening time (UTC)", str(record.get("created_at", "N/A"))],
        ["Workflow status", str(record.get("status", "N/A"))],
        ["Model version", str(record.get("model_version") or "No model configured")],
        ["AI output", str(record.get("grade_label") or "No prediction generated")],
    ]
    table = Table(data, colWidths=[45*mm, 120*mm])
    table.setStyle(TableStyle([
        ("BACKGROUND",(0,0),(0,-1),colors.HexColor("#EAF0F6")),
        ("GRID",(0,0),(-1,-1),0.4,colors.HexColor("#C8D1DB")),
        ("VALIGN",(0,0),(-1,-1),"TOP"),
        ("FONTNAME",(0,0),(-1,-1),"Helvetica"),
        ("FONTSIZE",(0,0),(-1,-1),9),
        ("LEFTPADDING",(0,0),(-1,-1),7),
        ("RIGHTPADDING",(0,0),(-1,-1),7),
        ("TOPPADDING",(0,0),(-1,-1),7),
        ("BOTTOMPADDING",(0,0),(-1,-1),7),
    ]))
    story += [table, Spacer(1, 8*mm), Paragraph("Interpretation and limitations", styles["Heading3"])]
    story.append(Paragraph(
        "This report records a software workflow and, if available, a research model output. "
        "It is not a diagnosis, cannot rule out diabetic retinopathy, and must not be used to make clinical decisions. "
        #"The model has not been clinically validated for rural Indian populations or the camera used. "
        #"An ungradable image requires recapture or assessment by a qualified eye-care professional. "
        "Seek appropriate clinical evaluation according to local care pathways.", styles["SmallNote"]))
    story += [Spacer(1, 5*mm), Paragraph("Generated by Drishti Care AI.", styles["SmallNote"])]
    doc.build(story)
    return buffer.getvalue()
